import { expect, test } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { invitePlayer, useAdmin } from "./account";

test("optional lifting, progress, private and shared performance boards on mobile", async ({ page }) => {
  await useAdmin(page);
  const link = await invitePlayer(page,"Performance Player");
  await page.setViewportSize({width:375,height:812});
  await page.goto(link);
  await page.getByLabel("Roster name").fill("Performance Player");
  await page.getByLabel("Position",{exact:true}).selectOption({label:"Fullback"});
  await page.getByRole("button",{name:"Save profile"}).click();
  await page.getByRole("link",{name:"Log",exact:true}).click();
  await page.getByRole("button",{name:"Weights",exact:true}).click();
  await page.getByLabel("Minutes",{exact:true}).fill("20");
  await page.getByText("Optional performance details",{exact:true}).click();
  await page.getByLabel("Calories",{exact:true}).fill("200");
  await page.getByRole("button",{name:"Add exercise",exact:true}).click();
  await page.getByLabel("Exercise",{exact:true}).selectOption("bench press");
  await page.getByLabel("Weight",{exact:true}).fill("135");
  await page.getByLabel("Reps",{exact:true}).fill("5");
  await page.getByRole("button",{name:"Save workout",exact:true}).click();
  await expect(page.getByText("Workout saved",{exact:true})).toBeVisible();
  await expect(page.getByText(/200 kcal/)).toBeVisible();
  await page.getByRole("link",{name:"You",exact:true}).click();
  await expect(page.getByRole("heading",{name:"My progress"})).toBeVisible();
  await expect(page.getByText("bench press PR",{exact:true})).toBeVisible();
  const sharing=page.getByLabel("Share my performance on team leaderboards");
  await expect(sharing).not.toBeChecked();
  await sharing.check();
  await expect(sharing).toBeEnabled();
  await page.getByRole("link",{name:"Board",exact:true}).click();
  await page.getByLabel("Leaderboard",{exact:true}).selectOption("strength");
  await expect(page.getByText("Performance Player",{exact:true})).toBeVisible();
  await page.getByLabel("Leaderboard",{exact:true}).selectOption("running");
  await expect(page.getByText("Performance Player",{exact:true})).toHaveCount(0);
  await page.getByLabel("Leaderboard",{exact:true}).selectOption("cycling");
  await expect(page.getByText("Performance Player",{exact:true})).toHaveCount(0);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  expect((await new AxeBuilder({page}).analyze()).violations).toEqual([]);
});
